"""Provider-independent LLM service interface and data contracts."""

from abc import ABC, abstractmethod
from enum import StrEnum
from typing import Any, Generic, TypeVar

from pydantic import BaseModel, Field

T = TypeVar("T", bound=BaseModel)


class MessageRole(StrEnum):
    """Standard message roles in LLM conversations."""

    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"
    TOOL = "tool"


class LLMMessage(BaseModel):
    """Standardized representation of a single conversation turn."""

    role: MessageRole = Field(..., description="Role of the message creator")
    content: str = Field(..., description="Text content of the message")
    name: str | None = Field(default=None, description="Optional author or tool name")
    tool_call_id: str | None = Field(
        default=None, description="Identifier of associated tool call when role is tool"
    )


class ToolDefinition(BaseModel):
    """Specification of an external tool callable by the model."""

    name: str = Field(..., description="Unique tool identifier")
    description: str = Field(..., description="Description of the tool purpose and usage")
    parameters: dict[str, Any] = Field(
        ..., description="JSON Schema defining the accepted input parameters"
    )


class ToolCallRequest(BaseModel):
    """Invocation request produced by the model."""

    id: str = Field(..., description="Unique tool call execution identifier")
    name: str = Field(..., description="Target tool name to invoke")
    arguments: dict[str, Any] = Field(
        default_factory=dict, description="Parsed arguments matching the tool schema"
    )


class TokenUsage(BaseModel):
    """Token consumption metrics for cost tracking and telemetry."""

    prompt_tokens: int = Field(default=0, ge=0)
    completion_tokens: int = Field(default=0, ge=0)
    total_tokens: int = Field(default=0, ge=0)
    cost_estimate_usd: float | None = Field(default=None, ge=0.0)


class LLMResponse(BaseModel):
    """Normalized response payload from an LLM inference call."""

    content: str | None = Field(default=None, description="Generated textual output")
    tool_calls: list[ToolCallRequest] = Field(
        default_factory=list, description="Tool invocations requested by the model"
    )
    usage: TokenUsage = Field(default_factory=TokenUsage, description="Token usage statistics")
    finish_reason: str = Field(default="stop", description="Model termination reason")
    model: str = Field(..., description="Model identifier that produced this completion")


class StructuredLLMResponse(BaseModel, Generic[T]):
    """Structured response parsed into a validated domain or schema model."""

    parsed: T = Field(..., description="Parsed and validated Pydantic model instance")
    raw_content: str = Field(..., description="Raw text generated by the model")
    usage: TokenUsage = Field(default_factory=TokenUsage, description="Token consumption metrics")
    model: str = Field(..., description="Model identifier that completed the request")


class BaseLLMClient(ABC):
    """Abstract interface defining required LLM capabilities for the research agent."""

    @abstractmethod
    async def generate_response(
        self,
        messages: list[LLMMessage],
        *,
        temperature: float = 0.2,
        max_tokens: int | None = None,
        model: str | None = None,
    ) -> LLMResponse:
        """Generate a standard conversational text response."""
        pass

    @abstractmethod
    async def generate_structured_response(
        self,
        messages: list[LLMMessage],
        response_model: type[T],
        *,
        temperature: float = 0.1,
        model: str | None = None,
    ) -> StructuredLLMResponse[T]:
        """Generate structured data parsed directly into a target Pydantic schema."""
        pass

    @abstractmethod
    async def generate_tool_calls(
        self,
        messages: list[LLMMessage],
        tools: list[ToolDefinition],
        *,
        temperature: float = 0.2,
        model: str | None = None,
    ) -> LLMResponse:
        """Evaluate messages against available tool definitions and return tool call requests."""
        pass
